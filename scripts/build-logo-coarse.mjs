#!/usr/bin/env node
/**
 * Generates the coarse mark: the halftone sun redrawn with 64 larger dots on concentric rings, for sizes under
 * 64px where the 325-dot original (`logo-dots.ts`, never redrawn) dissolves into a blob. Writes
 * components/ds/logo-dots-coarse.ts and app/icon.svg (the favicon). Both outputs are committed.
 */
import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

// Ring pitch, dot radius as a share of the pitch at the centre, outer radius, falloff curve, smallest dot kept.
const PITCH = 114;
const RATIO = 0.47;
const R = 572;
const FALLOFF = 1.3;
const MIN_R = 12;

const dots = [];
for (let k = 0; k * PITCH <= R; k++) {
  const d = k * PITCH;
  const r = PITCH * RATIO * (1 - (d / R) ** FALLOFF);
  if (r < MIN_R) break;
  const n = k === 0 ? 1 : Math.round((2 * Math.PI * d) / PITCH);
  for (let i = 0; i < n; i++) {
    const a = (2 * Math.PI * (i + 0.5 * k)) / n;
    dots.push([500 + d * Math.cos(a), 500 + d * Math.sin(a), r].map((v) => Math.round(v * 10) / 10));
  }
}

const flat = dots.flat().map((v) => v.toFixed(1)).join(',');
writeFileSync(
  resolve(root, 'components/ds/logo-dots-coarse.ts'),
  `/* The coarse mark: ${dots.length} dots on concentric rings for sizes under 64px. Generated by scripts/build-logo-coarse.mjs; edit the script, not this file. [cx, cy, r, ...] on a 1000-unit square. */\nexport const LOGO_DOTS_COARSE: readonly number[] = [${flat}];\n`,
);

const circles = dots.map(([cx, cy, r]) => `<circle cx="${cx}" cy="${cy}" r="${r}"/>`).join('\n');
writeFileSync(
  resolve(root, 'app/icon.svg'),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 1000" width="1000" height="1000" role="img" aria-label="Ambiently mark">\n<!-- The coarse mark (scripts/build-logo-coarse.mjs): ${dots.length} larger dots so the favicon reads as dots at 16 to 32px. Single ink #f9bb01. -->\n<g fill="#f9bb01">\n${circles}\n</g>\n</svg>\n`,
);
console.log(`Wrote ${dots.length} dots`);
